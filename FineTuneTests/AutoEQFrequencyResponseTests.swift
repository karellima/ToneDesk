    @Test("Single filter matches the RBJ reference (imported profile, no pre-warp)", arguments: references)
    func singleFilterMatchesReference(ref: Ref) {
        let filter = AutoEQFilter(type: ref.type, frequency: ref.fc, gainDB: ref.gain, q: ref.q)
        let c = BiquadMath.coefficientsForAutoEQFilters([filter], sampleRate: ref.rate, profileOptimizedRate: nil)
        for (f, expected) in zip(Self.probeFrequencies, ref.dB) {
            let actual = AutoEQTestSupport.magnitudeDB(coefficients: c, frequency: f, sampleRate: ref.rate)
            #expect(abs(actual - expected) < 0.001, "\(ref.testDescription) at \(f) Hz: \(actual) vs \(expected)")
        }
    }

    @Test("Analytic invariants: PK = G at Fc, shelves = G/2 at Fc, shelf plateau = G",
          arguments: [44100.0, 48000.0, 96000.0])
    func analyticInvariants(rate: Double) {
        for gain: Float in [-24, -12, -1.5, 3, 12, 24] {
            for q in [0.5, 0.71, 2.0, 6.0] {
                let pk = BiquadMath.coefficientsForAutoEQFilters(
                    [AutoEQFilter(type: .peaking, frequency: 1000, gainDB: gain, q: q)], sampleRate: rate, profileOptimizedRate: nil)
                #expect(abs(AutoEQTestSupport.magnitudeDB(coefficients: pk, frequency: 1000, sampleRate: rate) - Double(gain)) < 1e-6)

                let ls = BiquadMath.coefficientsForAutoEQFilters(
                    [AutoEQFilter(type: .lowShelf, frequency: 200, gainDB: gain, q: q)], sampleRate: rate, profileOptimizedRate: nil)
                #expect(abs(AutoEQTestSupport.magnitudeDB(coefficients: ls, frequency: 200, sampleRate: rate) - Double(gain) / 2) < 1e-6)
                #expect(abs(AutoEQTestSupport.magnitudeDB(coefficients: ls, frequency: 0.001, sampleRate: rate) - Double(gain)) < 1e-4)

                let hs = BiquadMath.coefficientsForAutoEQFilters(
                    [AutoEQFilter(type: .highShelf, frequency: 5000, gainDB: gain, q: q)], sampleRate: rate, profileOptimizedRate: nil)
                #expect(abs(AutoEQTestSupport.magnitudeDB(coefficients: hs, frequency: 5000, sampleRate: rate) - Double(gain) / 2) < 1e-6)
                #expect(abs(AutoEQTestSupport.magnitudeDB(coefficients: hs, frequency: rate / 2 - 0.001, sampleRate: rate) - Double(gain)) < 1e-4)
            }
        }
    }

    @Test("Imported profiles are not pre-warped: Fc is applied exactly as written at every rate",
          arguments: [44100.0, 48000.0, 96000.0])
    func importedProfilesUseExactFrequencies(rate: Double) throws {
        let text = "Preamp: -1 dB\nFilter 1: ON PK Fc 10000 Hz Gain -6.0 dB Q 2.0"
        let profile = try #require(AutoEQParser.parse(text: text, name: "t", source: .imported))
        #expect(profile.optimizedSampleRate == nil)
        let c = BiquadMath.coefficientsForAutoEQFilters(profile.filters, sampleRate: rate,
                                                        profileOptimizedRate: profile.optimizedSampleRate)
        #expect(abs(AutoEQTestSupport.magnitudeDB(coefficients: c, frequency: 10000, sampleRate: rate) + 6.0) < 1e-6)
    }

    @Test("Fetched AutoEQ-database profiles keep the 48 kHz pre-warp behavior")
    func fetchedProfilesKeepPreWarp() throws {
        let text = "Filter 1: ON PK Fc 10000 Hz Gain -6.0 dB Q 2.0"
        let profile = try #require(AutoEQParser.parse(text: text, name: "t", source: .fetched))
        #expect(profile.optimizedSampleRate == 48000)
    }

    @Test("Cascades with N filters: every filter contributes (sum of individual responses)",
          arguments: [12, 20, 32, 64])
    func cascadeAppliesAllFilters(count: Int) throws {
        let text = AutoEQTestSupport.syntheticProfileText(count: count)
        let profile = try #require(AutoEQParser.parse(text: text, name: "n\(count)", source: .imported))
        #expect(profile.filters.count == count)

        let rate = 48000.0
        let cascade = BiquadMath.coefficientsForAutoEQFilters(profile.filters, sampleRate: rate, profileOptimizedRate: nil)
        #expect(cascade.count == count * 5)

        // At each filter's own Fc the cascade response equals the sum of all individual
        // responses — dropping any filter would break this.
        for filter in profile.filters {
            let expected = profile.filters.reduce(0.0) { sum, f in
                let single = BiquadMath.coefficientsForAutoEQFilters([f], sampleRate: rate, profileOptimizedRate: nil)
                return sum + AutoEQTestSupport.magnitudeDB(coefficients: single, frequency: filter.frequency, sampleRate: rate)
            }
            let actual = AutoEQTestSupport.magnitudeDB(coefficients: cascade, frequency: filter.frequency, sampleRate: rate)
            #expect(abs(actual - expected) < 1e-6)
        }
        // The last filter is really there (would be missing under the old 10-filter cap).
        let last = try #require(profile.filters.last)
        let lastOnly = BiquadMath.coefficientsForAutoEQFilters([last], sampleRate: rate, profileOptimizedRate: nil)
        #expect(abs(AutoEQTestSupport.magnitudeDB(coefficients: lastOnly, frequency: last.frequency, sampleRate: rate) - Double(last.gainDB)) < 1e-6)
    }

    @Test("User REW profile (Harman, 10 filters): computed response at key frequencies")
    func userHarmanProfileResponse() throws {
        let profile = try #require(AutoEQParser.parse(
            text: try AutoEQTestSupport.fixtureText("1_Harman.txt"), name: "Harman", source: .imported))
        #expect(profile.filters.count == 10)
        #expect(profile.preampDB == -6.5)
        for rate in [44100.0, 48000.0, 96000.0] {
            let c = BiquadMath.coefficientsForAutoEQFilters(profile.filters, sampleRate: rate, profileOptimizedRate: nil)
            // 120 Hz notch (-10 dB Q5) on top of the +6 dB LSC (≈ +2.9 dB at 120 Hz) → deep cut
            let at120 = AutoEQTestSupport.magnitudeDB(coefficients: c, frequency: 120, sampleRate: rate)
            #expect(at120 < -6 && at120 > -9, "120 Hz at \(rate): \(at120)")
            // Bass shelf plateau around 30 Hz: LSC +6 minus the 55 Hz notch skirt
            let at30 = AutoEQTestSupport.magnitudeDB(coefficients: c, frequency: 30, sampleRate: rate)
            #expect(at30 > 5 && at30 < 6.5, "30 Hz at \(rate): \(at30)")
        }
    }
